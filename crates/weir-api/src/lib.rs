/// A connection's captured typed schema + any breaking-drift flag ([[WEIR-T-0121]]).
#[derive(serde::Serialize)]
struct SchemaView {
    fields: Vec<weir_app::Field>,
    /// The breaking-drift reason, if the schema is flagged; `null` when healthy.
    broken: Option<String>,
}

fn schema_of(app: &App, tenant: &str, name: &str) -> Result<SchemaView, ApiError> {
    let conn = app.get_connection(tenant, name)?;
    let fields = app
        .get_stream_schema(tenant, name, &conn.stream)?
        .map(|s| s.fields)
        .unwrap_or_default();
    let broken = app.schema_broken(tenant, name, &conn.stream)?;
    Ok(SchemaView { fields, broken })
}

