/// JSON view of a connection (source/dest as plugin names, config as raw JSON).
#[derive(Debug, Serialize, Deserialize)]
pub struct ConnectionDto {
    pub name: String,
    pub source: String,
    pub dest: String,
    pub stream: String,
    // `config` is the both-sides convenience ([[WEIR-I-0029]]); `source_config`/`dest_config` override
    // each side when present.
    #[serde(default = "empty_obj")]
    pub config: serde_json::Value,
    #[serde(default)]
    pub source_config: Option<serde_json::Value>,
    #[serde(default)]
    pub dest_config: Option<serde_json::Value>,
    #[serde(default)]
    pub every_secs: Option<f64>,
    #[serde(default)]
    pub cron: Option<String>,
    // Per-connection sync/write modes ([[WEIR-I-0028]]); defaults reproduce full-refresh + append.
    #[serde(default = "full_refresh")]
    pub sync_mode: String,
    #[serde(default = "append")]
    pub write_mode: String,
    #[serde(default)]
    pub business_keys: Vec<String>,
    #[serde(default)]
    pub cursor_field: Option<String>,
    // Execution mode ([[WEIR-I-0035]] F1): `run_once` (default) | `resident`.
    #[serde(default = "run_once")]
    pub execution_mode: String,
    // Read-only committed state (populated on list; ignored on create).
    #[serde(default)]
    pub cursor: Option<String>,
    #[serde(default)]
    pub chunks: i64,
    #[serde(default)]
    pub dead_lettered: i64,
}

fn empty_obj() -> serde_json::Value {
    serde_json::json!({})
}
fn full_refresh() -> String {
    "full_refresh".to_string()
}
fn append() -> String {
    "append".to_string()
}
fn run_once() -> String {
    "run_once".to_string()
}

impl ConnectionDto {
    fn into_connection(self) -> Connection {
        Connection {
            name: self.name,
            source: connector_ref(&self.source),
            dest: connector_ref(&self.dest),
            stream: self.stream,
            // Per-side config: the explicit override wins, else the `config` convenience for both.
            source_config: self
                .source_config
                .unwrap_or_else(|| self.config.clone())
                .to_string(),
            dest_config: self.dest_config.unwrap_or(self.config).to_string(),
            every_secs: self.every_secs,
            cron: self.cron,
            sync_mode: self.sync_mode,
            write_mode: self.write_mode,
            business_keys: self.business_keys,
            cursor_field: self.cursor_field,
            execution_mode: self.execution_mode,
        }
    }

    fn from_connection(c: &Connection) -> Self {
        Self {
            name: c.name.clone(),
            source: plugin_name(&c.source),
            dest: plugin_name(&c.dest),
            stream: c.stream.clone(),
            config: empty_obj(), // write-only convenience; the per-side configs carry the truth
            source_config: Some(
                serde_json::from_str(&c.source_config).unwrap_or_else(|_| empty_obj()),
            ),
            dest_config: Some(serde_json::from_str(&c.dest_config).unwrap_or_else(|_| empty_obj())),
            every_secs: c.every_secs,
            cron: c.cron.clone(),
            sync_mode: c.sync_mode.clone(),
            write_mode: c.write_mode.clone(),
            business_keys: c.business_keys.clone(),
            cursor_field: c.cursor_field.clone(),
            execution_mode: c.execution_mode.clone(),
            cursor: None,
            chunks: 0,
            dead_lettered: 0,
        }
    }
}

