// Prometheus metrics ([[WEIR-T-0099]]): install the global recorder once; `/metrics` renders the text.
static METRICS_HANDLE: std::sync::OnceLock<metrics_exporter_prometheus::PrometheusHandle> =
    std::sync::OnceLock::new();

fn metrics_handle() -> &'static metrics_exporter_prometheus::PrometheusHandle {
    METRICS_HANDLE.get_or_init(|| {
        metrics_exporter_prometheus::PrometheusBuilder::new()
            .install_recorder()
            .expect("install prometheus recorder")
    })
}

/// `GET /metrics` — public (like `/health`), Prometheus text format. The run path emits to the global
/// recorder ([[WEIR-T-0099]]); aggregate labels by default (no tenant leak).
async fn metrics_handler() -> Response {
    (
        [(header::CONTENT_TYPE, "text/plain; version=0.0.4")],
        metrics_handle().render(),
    )
        .into_response()
}

