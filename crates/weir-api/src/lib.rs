/// Import request — exactly one of: `path` (local crate, compiled), `package`
/// (already-staged folder), or `manifest` (declarative yaml, registered instantly).
#[derive(Deserialize)]
struct ImportDto {
    path: Option<String>,
    package: Option<String>,
    manifest: Option<String>,
    /// A vendored manifest selected by name from `/catalog/available` (read + import).
    manifest_name: Option<String>,
    /// A vendored **destination** manifest selected by name ([[WEIR-I-0015]]).
    dest_manifest_name: Option<String>,
    /// Optional name for a `manifest` import (else derived from the manifest).
    name: Option<String>,
}

/// Import (register) a connector via the ingress pipeline; `origin = private`.
async fn catalog_import(
    State(app): State<Arc<App>>,
    axum::Extension(key): axum::Extension<AuthenticatedKey>,
    Json(dto): Json<ImportDto>,
) -> Result<Json<CatalogEntry>, ApiError> {
    let tenant = tenant_of(&key);
    // A vendored manifest picked by name (discover & select) → read + onboard.
    if let Some(mname) = dto.manifest_name {
        return Ok(Json(app.import_vendored_manifest(
            tenant,
            &mname,
            Origin::Community,
        )?));
    }
    // A vendored **destination** manifest picked by name → onboard as rest-dest ([[WEIR-I-0015]]).
    if let Some(dname) = dto.dest_manifest_name {
        return Ok(Json(app.import_vendored_dest_manifest(
            tenant,
            &dname,
            Origin::Community,
        )?));
    }
    let source = match (dto.path, dto.package, dto.manifest) {
        (Some(p), _, _) => Source::LocalCrate(p.into()),
        (_, Some(pkg), _) => Source::Folder { package: pkg },
        (_, _, Some(yaml)) => Source::Manifest {
            yaml,
            name: dto.name,
        },
        _ => {
            return Err(ApiError(
                StatusCode::BAD_REQUEST,
                "`path`, `package`, or `manifest` required".into(),
            ));
        }
    };
    Ok(Json(app.import(tenant, source, Origin::Private)?))
}

