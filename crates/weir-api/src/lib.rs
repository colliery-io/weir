/// Build the control-plane router over a shared [`App`]. The API routes require a valid
/// `Authorization: Bearer <api-key>` ([[WEIR-A-0008]] / [[WEIR-T-0084]], mirroring cloacina);
/// `/health` + the SPA fallback are registered outside the auth layer and stay public.
pub fn router(app: Arc<App>) -> Router {
    // Install the Prometheus recorder before the worker emits ([[WEIR-T-0099]]).
    let _ = metrics_handle();
    let auth = AuthState {
        app: Arc::clone(&app),
        cache: Arc::new(KeyCache::new(256, Duration::from_secs(30))),
    };
    let api = Router::new()
        .route("/connections", get(list).post(create))
        .route("/connections/{name}", get(fetch).delete(remove))
        .route("/connections/{name}/run", post(run))
        .route("/connections/{name}/start", post(start))
        .route("/connections/{name}/stop", post(stop))
        .route("/connections/{name}/runs", get(runs))
        .route("/connections/{name}/dead-letters", get(dead_letters))
        .route("/connections/{name}/logs", get(logs))
        .route("/connections/{name}/state", get(state))
        // Typed schema + drift ([[WEIR-T-0121]] / [[WEIR-I-0025]]).
        .route("/connections/{name}/schema", get(schema_view))
        .route("/connections/{name}/schema/accept", post(schema_accept))
        .route("/connectors/{plugin}/spec", get(connector_spec))
        .route("/connectors/{plugin}/discover", post(connector_discover))
        // Connector catalog ([[WEIR-I-0010]] S3): registered list, folder-scan
        // availability, import (ingress), unregister.
        .route("/catalog", get(catalog_list))
        .route("/catalog/available", get(catalog_available))
        .route("/catalog/import", post(catalog_import))
        .route("/catalog/preview", post(catalog_preview))
        .route("/catalog/{name}/{version}", delete(catalog_unregister))
        .route("/runs", get(recent))
        // Holistic ops health ([[WEIR-T-0110]] / [[WEIR-I-0024]]) — implicit-tenant per-connection health.
        .route("/overview", get(overview))
        // Tenant administration (platform-admin only — [[WEIR-T-0090]]).
        .route("/tenants", get(tenants_list).post(tenants_create))
        .route("/tenants/{id}", delete(tenants_delete))
        .route("/tenants/{id}/keys", get(tenant_keys_list).post(tenant_keys_create))
        .route("/tenants/{id}/keys/{kid}", delete(tenant_keys_revoke))
        // Admin cross-tenant data browse ([[WEIR-T-0094]]) — the switcher's target.
        .route("/tenants/{id}/connections", get(t_connections))
        .route("/tenants/{id}/connections/{name}", get(t_connection))
        .route("/tenants/{id}/connections/{name}/run", post(t_run))
        .route("/tenants/{id}/connections/{name}/start", post(t_start))
        .route("/tenants/{id}/connections/{name}/stop", post(t_stop))
        .route("/tenants/{id}/connections/{name}/runs", get(t_runs))
        .route("/tenants/{id}/connections/{name}/dead-letters", get(t_dead_letters))
        .route("/tenants/{id}/connections/{name}/logs", get(t_logs))
        .route("/tenants/{id}/connections/{name}/state", get(t_state))
        .route("/tenants/{id}/catalog", get(t_catalog))
        .route("/tenants/{id}/runs", get(t_recent))
        // Explicit-tenant health (admin cross-tenant) + the platform-wide rollup ([[WEIR-T-0110]]).
        .route("/tenants/{id}/overview", get(t_overview))
        .route("/platform/health", get(platform_overview))
        .route("/auth/me", get(auth_me))
        // Layers run outermost-first: AuthN resolves the key, then AuthZ + audit gate the route.
        .route_layer(axum::middleware::from_fn_with_state(Arc::clone(&app), authz::authz_mw))
        .route_layer(axum::middleware::from_fn_with_state(auth, require_auth));
    // Public OIDC routes carry their own state (config + in-flight login store + lazily-discovered
    // provider); the SPA fallback + /health + /auth/logout are public too.
    let oidc_routes = Router::new()
        .route("/auth/login", get(oidc::auth_login))
        .route("/auth/callback", get(oidc::auth_callback))
        .with_state(oidc::OidcState::from_env(Arc::clone(&app)));
    Router::new()
        .route("/health", get(|| async { "ok" }))
        .route("/metrics", get(metrics_handler))
        .route("/auth/logout", get(auth_logout))
        .merge(oidc_routes)
        .merge(api)
        .fallback(serve_ui)
        .with_state(app)
        // Outermost: log every request's method + full path + status (`RUST_LOG=weir_api=debug`).
        .layer(axum::middleware::from_fn(log_request))
}

/// Lightweight access log ([[WEIR-I-0035]] F1 diagnostics): method, the FULL path (so
/// tenant-scoped `/tenants/{id}/runs` vs `/runs` is visible), and the response status.
/// Bodies are never logged — this stays cheap on the hot path.
async fn log_request(req: Request, next: Next) -> Response {
    let method = req.method().clone();
    let path = req
        .uri()
        .path_and_query()
        .map(|pq| pq.as_str().to_owned())
        .unwrap_or_else(|| req.uri().path().to_owned());
    let resp = next.run(req).await;
    tracing::debug!(target: "weir_api::http", method = %method, path = %path, status = %resp.status().as_u16(), "http request");
    resp
}

/// A validated key cached with a TTL (cloacina's `KeyCache`, `routes/auth.rs`).
struct CachedKey {
    key: AuthenticatedKey,
    at: Instant,
}

/// LRU cache of validated keys (by SHA-256 hash) with TTL expiry — skips the DB on hot paths.
struct KeyCache {
    cache: Mutex<LruCache<String, CachedKey>>,
    ttl: Duration,
}

impl KeyCache {
    fn new(capacity: usize, ttl: Duration) -> Self {
        Self {
            cache: Mutex::new(LruCache::new(
                std::num::NonZeroUsize::new(capacity).expect("cache capacity > 0"),
            )),
            ttl,
        }
    }

    async fn get(&self, hash: &str) -> Option<AuthenticatedKey> {
        let mut c = self.cache.lock().await;
        if let Some(entry) = c.get(hash) {
            if entry.at.elapsed() < self.ttl {
                return Some(entry.key.clone());
            }
            c.pop(hash);
        }
        None
    }

    async fn insert(&self, hash: String, key: AuthenticatedKey) {
        self.cache.lock().await.put(
            hash,
            CachedKey {
                key,
                at: Instant::now(),
            },
        );
    }
}

#[derive(Clone)]
struct AuthState {
    app: Arc<App>,
    cache: Arc<KeyCache>,
}

/// AuthN layer: require `Authorization: Bearer <api-key>`. Checks the LRU cache, else validates
/// against the store; on success inserts an [`AuthenticatedKey`] extension (for [[WEIR-T-0085]]
/// authz + audit); else 401.
async fn require_auth(State(auth): State<AuthState>, mut req: Request, next: Next) -> Response {
    // Two doors ([[WEIR-A-0008]]): the `Authorization: Bearer` header (machines) or the
    // `weir_session` cookie holding an OIDC-minted key (humans, [[WEIR-T-0086]]).
    let presented = req
        .headers()
        .get(header::AUTHORIZATION)
        .and_then(|v| v.to_str().ok())
        .and_then(|s| s.strip_prefix("Bearer "))
        // An empty bearer (the UI sends one when no key is stored) must fall through to the cookie.
        .filter(|s| !s.is_empty())
        .map(str::to_owned)
        .or_else(|| session_cookie(req.headers()));
    let Some(key) = presented else {
        return unauthorized();
    };
    let hash = weir_app::auth::hash_api_key(&key);
    let authed = match auth.cache.get(&hash).await {
        Some(k) => Some(k),
        None => match auth.app.validate_api_key(&key) {
            Ok(Some(k)) => {
                auth.cache.insert(hash, k.clone()).await;
                Some(k)
            }
            _ => None,
        },
    };
    match authed {
        Some(k) => {
            req.extensions_mut().insert(k);
            next.run(req).await
        }
        None => unauthorized(),
    }
}

fn unauthorized() -> Response {
    (
        StatusCode::UNAUTHORIZED,
        Json(serde_json::json!({
            "error": "unauthorized: present a valid `Authorization: Bearer <api-key>`"
        })),
    )
        .into_response()
}

/// Read the `weir_session` cookie ([[WEIR-T-0086]], the human 2nd door — it holds an OIDC-minted key).
fn session_cookie(headers: &axum::http::HeaderMap) -> Option<String> {
    headers
        .get(header::COOKIE)?
        .to_str()
        .ok()?
        .split(';')
        .filter_map(|kv| kv.trim().split_once('='))
        .find(|(k, _)| *k == "weir_session")
        .map(|(_, v)| v.to_string())
}

/// `GET /auth/me` — the current principal, for the UI sign-in gate ([[WEIR-T-0087]]). Authenticated.
async fn auth_me(
    axum::Extension(key): axum::Extension<AuthenticatedKey>,
) -> Json<serde_json::Value> {
    Json(serde_json::json!({
        "subject": format!("key:{}", key.name),
        "name": key.name,
        "role": key.permissions,
        "tenant": key.tenant_id,
        "is_admin": key.is_admin,
    }))
}

/// `GET /auth/logout` — clear the session cookie. Public (works even with an expired session).
async fn auth_logout() -> Response {
    (
        [(
            header::SET_COOKIE,
            "weir_session=; Path=/; HttpOnly; SameSite=Lax; Max-Age=0",
        )],
        Json(serde_json::json!({ "ok": true })),
    )
        .into_response()
}

const FALLBACK_HTML: &str = "<!doctype html><html><head><meta charset=\"utf-8\"><title>weir</title></head>\
<body style=\"font-family:system-ui;background:#0e1116;color:#e6edf3;padding:40px\">\
<h1>weir</h1><p>The web UI isn't built into this binary. Run <code>trunk build</code> in \
<code>weir-ui/</code> and rebuild.</p></body></html>";

/// Serve the embedded Leptos UI (assets + SPA fallback). Falls back to a small
/// placeholder when the UI hasn't been built into the binary.
async fn serve_ui(uri: Uri) -> Response {
    let path = uri.path().trim_start_matches('/');
    let path = if path.is_empty() { "index.html" } else { path };

    if let Some((_, bytes)) = UI_FILES.iter().find(|(p, _)| *p == path) {
        return ([(header::CONTENT_TYPE, content_type(path))], *bytes).into_response();
    }
    // SPA fallback to index.html if the UI is embedded; else the placeholder.
    if let Some((_, bytes)) = UI_FILES.iter().find(|(p, _)| *p == "index.html") {
        return ([(header::CONTENT_TYPE, "text/html")], *bytes).into_response();
    }
    ([(header::CONTENT_TYPE, "text/html")], FALLBACK_HTML).into_response()
}

fn content_type(path: &str) -> &'static str {
    match path.rsplit('.').next() {
        Some("html") => "text/html",
        Some("js") => "text/javascript",
        Some("wasm") => "application/wasm",
        Some("css") => "text/css",
        Some("json") => "application/json",
        _ => "application/octet-stream",
    }
}

/// Serve the API on `port` until the process exits. Single-node: a background task
/// runs the **scheduler + worker** in-process (`App::serve`, 100 ms poll) so
/// scheduled connections fire (sub-second intervals supported, [[WEIR-T-0051]]),
/// UI add/edit is reconciled live, and triggered runs drain asynchronously — the UI
/// watches them go pending → done/failed in real time.
pub async fn serve(app: Arc<App>, port: u16, concurrency: usize) -> std::io::Result<()> {
    let bg = Arc::clone(&app);
    tokio::spawn(async move {
        let _ = bg
            .serve(
                std::time::Duration::from_millis(100),
                concurrency,
                std::future::pending::<()>(),
            )
            .await;
    });
    let listener = tokio::net::TcpListener::bind(("0.0.0.0", port)).await?;
    axum::serve(listener, router(app)).await
}

/// The caller's tenant, taken implicitly from their key ([[WEIR-A-0036]] decision 3). A global key
/// (no `tenant_id`) acts on the `default` tenant. Handlers scope all data by this.
fn tenant_of(key: &AuthenticatedKey) -> &str {
    key.tenant_id.as_deref().unwrap_or(weir_app::DEFAULT_TENANT)
}

async fn list(
    State(app): State<Arc<App>>,
    axum::Extension(key): axum::Extension<AuthenticatedKey>,
) -> Result<Json<Vec<ConnectionDto>>, ApiError> {
    let tenant = tenant_of(&key);
    let mut dtos = Vec::new();
    for c in app.list_connections(tenant)? {
        let mut dto = ConnectionDto::from_connection(&c);
        // Enrich with the committed resume point + progress for the card viz.
        if let Ok(st) = app.connection_state(tenant, &c.name) {
            dto.cursor = st.cursor;
            dto.chunks = st.chunks;
            dto.dead_lettered = st.dead_lettered;
        }
        dtos.push(dto);
    }
    Ok(Json(dtos))
}

async fn create(
    State(app): State<Arc<App>>,
    axum::Extension(key): axum::Extension<AuthenticatedKey>,
    Json(dto): Json<ConnectionDto>,
) -> Result<StatusCode, ApiError> {
    app.add_connection(tenant_of(&key), &dto.into_connection())?;
    Ok(StatusCode::CREATED)
}

